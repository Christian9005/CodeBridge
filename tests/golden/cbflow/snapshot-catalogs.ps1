# Records what the blocks of a release looked like (ports, properties, defaults, choices) in catalogs.json, so a test can make sure later versions keep
# everything the flows saved with that release rely on.
#
#   pwsh tests/golden/cbflow/snapshot-catalogs.ps1 -Version 0.7.0 -Ref v0.7.0
#
# Run it once for every release (a tag, or the commit the release was built from) and commit the result. An existing version is replaced.
param(
    [Parameter(Mandatory)][string]$Version,
    [Parameter(Mandatory)][string]$Ref,
    [string[]]$Boards = @('esp32-devkit', 'arduino-uno')
)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$repo = (git -C $here rev-parse --show-toplevel).Trim()
$file = Join-Path $here 'catalogs.json'

function Read-Catalog([string]$board) {
    $path = "src/CodeBridge.VisualStudio/Assets/catalog.$board.json"
    $json = git -C $repo show "${Ref}:$path" 2>$null
    if ($LASTEXITCODE -ne 0 -or -not $json) { return $null }
    ($json -join "`n").TrimStart([char]0xFEFF) | ConvertFrom-Json
}

$release = [ordered]@{ version = $Version; ref = (git -C $repo rev-parse --short $Ref).Trim(); boards = [ordered]@{} }
foreach ($board in $Boards) {
    $catalog = Read-Catalog $board
    if (-not $catalog) { Write-Warning "$board has no catalog at $Ref"; continue }
    $blocks = [ordered]@{}
    foreach ($block in ($catalog.blocks | Sort-Object type)) {
        $blocks[$block.type] = [ordered]@{
            ports      = @($block.ports | ForEach-Object { [ordered]@{ name = $_.name; direction = "$($_.direction)"; kind = "$($_.valueKind)"; required = [bool]$_.required } })
            properties = @($block.properties | ForEach-Object {
                    [ordered]@{
                        name     = $_.name
                        kind     = "$($_.valueKind)"
                        required = [bool]$_.required
                        default  = $_.defaultValue
                        choices  = @($_.options | Where-Object { $null -ne $_ } | ForEach-Object { $_.value })
                    }
                })
        }
    }
    $release.boards[$board] = $blocks
}

$all = if (Test-Path $file) { @((Get-Content $file -Raw | ConvertFrom-Json).releases) } else { @() }
$all = @($all | Where-Object { $_.version -ne $Version }) + [pscustomobject]$release
$all = $all | Sort-Object { [version]($_.version -replace '[^\d.].*$', '') }
$text = [pscustomobject]@{ note = 'Generated by snapshot-catalogs.ps1. Do not edit by hand.'; releases = @($all) } | ConvertTo-Json -Depth 12
[System.IO.File]::WriteAllText($file, $text + "`n", (New-Object System.Text.UTF8Encoding($false)))
"{0}: {1} board(s), {2} block(s) on {3}" -f $Version, $release.boards.Count, (($release.boards.Values | Select-Object -First 1).Count), ($release.boards.Keys | Select-Object -First 1)
